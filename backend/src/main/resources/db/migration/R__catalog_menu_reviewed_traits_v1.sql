SELECT m.data_version, m.menu_id, r.sweetness, r.sweetness_evidence,
       CASE WHEN r.signature_evidence IS NOT NULL THEN TRUE END AS is_signature,
       r.signature_evidence
FROM catalog_active a
JOIN catalog_menu m ON m.data_version = a.data_version
LEFT JOIN reviewed r ON r.menu_id = m.menu_id
    AND r.cafe_id = m.cafe_id
    AND r.original_name = m.name
    AND r.original_description IS NOT DISTINCT FROM m.description
WHERE a.singleton_id = 1;
